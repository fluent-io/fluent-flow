CREATE TABLE agent_claim_events (
  org_id text NOT NULL REFERENCES orgs (id),
  claim_id integer NOT NULL REFERENCES agent_claims (id) ON DELETE CASCADE,
  seq integer NOT NULL,
  kind text NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, claim_id, seq)
);

CREATE TABLE agent_claim_requests (
  org_id text NOT NULL REFERENCES orgs (id),
  claim_id integer NOT NULL REFERENCES agent_claims (id) ON DELETE CASCADE,
  request_key text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('permission', 'elicitation')),
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'answer_queued', 'resolved', 'uncertain', 'cancelled')),
  response jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  PRIMARY KEY (org_id, claim_id, request_key)
);

CREATE TABLE agent_claim_commands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id text NOT NULL REFERENCES orgs (id),
  claim_id integer NOT NULL REFERENCES agent_claims (id) ON DELETE CASCADE,
  idempotency_key text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('prompt', 'cancel', 'permission', 'elicitation')),
  payload jsonb NOT NULL,
  request_key text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'delivered', 'acked', 'failed', 'uncertain', 'cancelled')),
  result jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  delivered_at timestamptz,
  acked_at timestamptz,
  UNIQUE (org_id, claim_id, idempotency_key)
);

CREATE INDEX agent_claim_commands_pending_idx
  ON agent_claim_commands (org_id, claim_id, created_at, id)
  WHERE status = 'pending';

CREATE TABLE collab_claim_executions (
  task_id uuid NOT NULL REFERENCES collab_tasks (id),
  project_id uuid NOT NULL REFERENCES collab_projects (id),
  claim_id integer NOT NULL UNIQUE REFERENCES agent_claims (id) ON DELETE CASCADE,
  root_claim_id integer NOT NULL REFERENCES agent_claims (id),
  created_by_principal_id uuid NOT NULL REFERENCES collab_principals (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (task_id, claim_id)
);

CREATE INDEX collab_claim_executions_task_idx ON collab_claim_executions (task_id, created_at, claim_id);
CREATE INDEX collab_claim_executions_root_claim_idx ON collab_claim_executions (root_claim_id);
